def write_markdown(path):
    """将既有登录用例按模块导出为可阅读的Markdown清单。"""
    lines = ["# Web UI 已登录－未订阅测试用例", "", "环境：连接的 iPhone 普通 Chrome；游客状态由网页登录状态区分。仅验证订阅入口，不购买。举报和拉黑最后执行。", "", "来电与轮播按账号、数据条件分支执行；未满足条件不计为通过。新旧账号必须有界面或其他可靠依据。", ""]
    groups = dict.fromkeys(item[1] for item in CASES)
    for group in groups:
        lines += [f"## {group}", ""]
        for case_id, module, title, steps, expected in CASES:
            if module != group:
                continue
            lines += [f"### {case_id} {title}", "", "- 测试步骤"]
            lines += [f"  - {i}、{text}" for i, text in enumerate(steps, 1)]
            lines += ["- 预期结果"]
            lines += [f"  - {i}、{text}" for i, text in enumerate(expected, 1)]
            lines += [""]
    path.write_text("\n".join(lines), encoding="utf-8")
