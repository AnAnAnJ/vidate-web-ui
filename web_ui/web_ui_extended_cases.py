def validate_order(case_ids):
    """校验订阅项只能出现在所有未标记项之后，返回合法执行序列。"""
    subscribed_started = False
    for case_id in case_ids:
        if case_id in SUBSCRIBED_IDS:
            subscribed_started = True
        elif subscribed_started:
            raise ValueError('所有未标记用例必须在已订阅用例之前处理')
    return list(case_ids)


